/**
 * Transactions-only command endpoint.
 * Appends caller-provided rows to Transactions!B:L. `POST ?action=resolveamount`
 * updates only the Resolved Amount cell of one existing Transactions row.
 */
import 'jsr:@supabase/functions-js/edge-runtime.d.ts'
import { getSheetContext, sheetHeaders, SheetContextError } from '../_shared/sheetContext.ts'
import { sortTransactionsByDate } from '../_shared/sortTransactions.ts'

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
}

interface TransactionInput {
  date: string
  account: string
  amount: number
  currency: string
  targetAccount: string
  type: string
  category: string
  subcategory: string
  budget: string
  note: string
}

interface TxBody { transactions?: TransactionInput[] }

interface ResolveAmountBody {
  transactionId?: string
  resolvedAmount?: number
}

function isTransaction(value: unknown): value is TransactionInput {
  if (!value || typeof value !== 'object') return false
  const tx = value as Record<string, unknown>
  return typeof tx.date === 'string' && tx.date.trim() !== '' &&
    typeof tx.account === 'string' && tx.account.trim() !== '' &&
    typeof tx.amount === 'number' && Number.isFinite(tx.amount) && tx.amount > 0 &&
    typeof tx.currency === 'string' && tx.currency.trim() !== '' &&
    typeof tx.targetAccount === 'string' && typeof tx.type === 'string' && tx.type.trim() !== '' &&
    typeof tx.category === 'string' && tx.category.trim() !== '' && typeof tx.subcategory === 'string' &&
    typeof tx.budget === 'string' && typeof tx.note === 'string'
}

function isResolveAmountBody(value: unknown): value is Required<ResolveAmountBody> {
  if (!value || typeof value !== 'object') return false
  const body = value as Record<string, unknown>
  return typeof body.transactionId === 'string' && body.transactionId.trim() !== '' &&
    typeof body.resolvedAmount === 'number' && Number.isFinite(body.resolvedAmount) && body.resolvedAmount > 0
}

/** Converts transport objects to Transactions-sheet columns B:L. */
export function toTransactionRows(transactions: TransactionInput[]): string[][] {
  return transactions.map((tx) => [
    tx.date.trim(), tx.account.trim(), tx.amount.toFixed(2), '', tx.currency.trim(),
    tx.targetAccount.trim(), tx.type.trim(), tx.category.trim(), tx.subcategory.trim(),
    tx.budget.trim(), tx.note.trim(),
  ])
}

Deno.serve(async (req: Request) => {
  if (req.method === 'OPTIONS') return new Response(null, { headers: CORS_HEADERS })
  if (req.method !== 'POST') return Response.json({ error: 'Method not allowed' }, { status: 405, headers: CORS_HEADERS })

  try {
    const action = new URL(req.url).searchParams.get('action')
    if (action !== null && action !== 'resolveamount') {
      return Response.json({ error: 'Unknown action' }, { status: 400, headers: CORS_HEADERS })
    }

    let body: TxBody | ResolveAmountBody
    try { body = await req.json() as TxBody } catch {
      return Response.json({ error: 'Malformed JSON body' }, { status: 400, headers: CORS_HEADERS })
    }

    const { sheetId, accessToken } = await getSheetContext(req.headers.get('Authorization'))

    if (action === 'resolveamount') {
      if (!isResolveAmountBody(body)) {
        return Response.json({ error: 'Invalid resolution details' }, { status: 400, headers: CORS_HEADERS })
      }
      // Txn IDs in column A are regenerated by the sheet after a date sort, so
      // resolve the current row from its present value immediately before write.
      const readRes = await fetch(
        `https://sheets.googleapis.com/v4/spreadsheets/${sheetId}/values/${encodeURIComponent('Transactions!A2:A')}`,
        { headers: { Authorization: `Bearer ${accessToken}` } },
      )
      if (!readRes.ok) return Response.json({ error: 'Failed to read transactions' }, { status: 502, headers: CORS_HEADERS })
      const { values = [] } = await readRes.json() as { values?: string[][] }
      const rowIndex = values.findIndex((row) => row[0]?.trim() === body.transactionId.trim())
      if (rowIndex === -1) return Response.json({ error: 'Transaction not found' }, { status: 404, headers: CORS_HEADERS })

      const row = rowIndex + 2
      const writeRes = await fetch(
        `https://sheets.googleapis.com/v4/spreadsheets/${sheetId}/values/${encodeURIComponent(`Transactions!E${row}`)}?valueInputOption=USER_ENTERED`,
        {
          method: 'PUT',
          headers: sheetHeaders(accessToken),
          body: JSON.stringify({ values: [[body.resolvedAmount.toFixed(2)]] }),
        },
      )
      if (!writeRes.ok) return Response.json({ error: 'Failed to resolve transaction amount' }, { status: 502, headers: CORS_HEADERS })
      return new Response(null, { status: 201, headers: CORS_HEADERS })
    }

    const transactions = (body as TxBody).transactions
    if (!Array.isArray(transactions) || transactions.length === 0 || !transactions.every(isTransaction)) {
      return Response.json({ error: 'Invalid transaction rows' }, { status: 400, headers: CORS_HEADERS })
    }

    // `values.append` detects the whole logical table and can start at its
    // first column (A), even when passed B:L. Read the populated B column and
    // update an explicit B:L range instead, preserving the Txn ID formula in A.
    const existingRes = await fetch(
      `https://sheets.googleapis.com/v4/spreadsheets/${sheetId}/values/${encodeURIComponent('Transactions!B2:B')}`,
      { headers: { Authorization: `Bearer ${accessToken}` } },
    )
    if (!existingRes.ok) return Response.json({ error: 'Failed to read transactions' }, { status: 502, headers: CORS_HEADERS })
    const existing = await existingRes.json() as { values?: string[][] }
    const firstOpenRow = 2 + (existing.values?.length ?? 0)
    const lastRow = firstOpenRow + transactions.length - 1
    const writeRange = `Transactions!B${firstOpenRow}:L${lastRow}`
    const writeRes = await fetch(
      `https://sheets.googleapis.com/v4/spreadsheets/${sheetId}/values/${encodeURIComponent(writeRange)}?valueInputOption=USER_ENTERED`,
      {
        method: 'PUT', headers: sheetHeaders(accessToken),
        body: JSON.stringify({ majorDimension: 'ROWS', values: toTransactionRows(transactions) }),
      },
    )
    if (!writeRes.ok) return Response.json({ error: 'Failed to write transactions' }, { status: 502, headers: CORS_HEADERS })
    try {
      await sortTransactionsByDate(accessToken, sheetId)
    } catch {
      return Response.json({ error: 'Transactions inserted but failed to sort by date' }, { status: 502, headers: CORS_HEADERS })
    }
    return Response.json({ ok: true, tx: transactions.length }, { status: 201, headers: CORS_HEADERS })
  } catch (error) {
    if (error instanceof SheetContextError) {
      return Response.json({ error: error.message }, { status: error.status, headers: CORS_HEADERS })
    }
    console.error('Unexpected error:', error)
    return Response.json({ error: 'Unexpected server error' }, { status: 500, headers: CORS_HEADERS })
  }
})
